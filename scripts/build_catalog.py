#!/usr/bin/env python3
"""Generate CATALOG.md (all skills grouped by category, with description and source)."""
import csv, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from validate_skills import parse, ROOT

REPO = ROOT.parent
ORDER = ["core", "workflow", "design", "architecture", "security", "dotnet", "database",
         "devops", "testing", "automation", "meta"]
TITLES = {
    "core": "Core — my style & system building (start here)",
    "workflow": "Workflow — planning, TDD, debugging, review",
    "design": "Design — UI/UX, design systems, frontend",
    "architecture": "Architecture & Backend",
    "security": "Security",
    "dotnet": ".NET / C#",
    "database": "Databases — SQL Server, SQLite, SQL",
    "devops": "DevOps, CI/CD & Observability",
    "testing": "Testing",
    "automation": "Automation — n8n, scripts, jobs",
    "meta": "Meta — writing new skills",
}

sources = {}
with open(REPO / "sources.tsv", encoding="utf-8") as f:
    for row in csv.DictReader(f, delimiter="\t"):
        sources[row["skill"]] = row

def short(desc, n=220):
    desc = " ".join(desc.split())
    return desc if len(desc) <= n else desc[: n - 1].rsplit(" ", 1)[0] + "…"

lines = ["# Skills Catalog", "",
         "> Auto-generated by `scripts/build_catalog.py` — do not edit by hand.", ""]
total = 0
cats = sorted({p.parent.parent.name for p in ROOT.glob("*/*/SKILL.md")},
              key=lambda c: ORDER.index(c) if c in ORDER else 99)
for cat in cats:
    skills = sorted(ROOT.glob(f"{cat}/*/SKILL.md"))
    lines += [f"## {TITLES.get(cat, cat)} ({len(skills)})", "",
              "| Skill | What it does | Source |", "|---|---|---|"]
    for p in skills:
        meta = parse(p.read_text(encoding="utf-8")) or {}
        name = p.parent.name
        src = sources.get(name, {})
        repo = src.get("upstream_repo", "?")
        src_md = "**original**" if repo == "original" else f"[{repo}](https://github.com/{repo})"
        desc = short(meta.get("description", "")).replace("|", "\\|")
        lines.append(f"| [`{name}`](skills/{cat}/{name}/SKILL.md) | {desc} | {src_md} |")
        total += 1
    lines.append("")
lines.insert(4, f"**Total skills: {total}**\n")
(REPO / "CATALOG.md").write_text("\n".join(lines), encoding="utf-8")
print(f"CATALOG.md written ({total} skills)")
